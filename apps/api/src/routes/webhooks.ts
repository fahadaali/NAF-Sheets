// POST /webhooks/basecamp/:secret — Basecamp webhook deliveries (spec §9.3.2–3).
//
// Public path: Basecamp signs nothing, so the secret in the path is the only
// check here. The delivery is queued raw and answered 200 at once; the queue
// consumer verifies `recording.bucket.id` against the project and always
// fetches the record from Basecamp before acting (§9.3.2, §9.3.4).
//
// Basecamp retries non-2xx up to 10 times and then disables the webhook, and
// never follows 3xx (Appendix A-6) — hence no redirect and no slow work here.

import { Hono } from 'hono'
import type { AppEnv } from '../auth'
import { ApiFailure } from '../errors'
import { nowIso } from '../request'

/** Secrets are generated by the platform: URL-safe, at least 32 characters. */
const SECRET_PATTERN = /^[A-Za-z0-9_-]{32,128}$/

export function webhookRoutes(): Hono<AppEnv> {
  const routes = new Hono<AppEnv>()

  routes.post('/basecamp/:secret', async (c) => {
    const secret = c.req.param('secret')
    if (!SECRET_PATTERN.test(secret)) throw new ApiFailure(404, 'webhook_not_found')

    // OPEN: the secret is stored as the spec names it (`secret`), not hashed (OPEN_QUESTIONS.md #15).
    const hook = await c.env.DB.prepare('SELECT bc_webhook_id, bc_project_id FROM bc_webhooks WHERE secret = ?1')
      .bind(secret)
      .first<{ bc_webhook_id: number; bc_project_id: number }>()
    if (!hook) throw new ApiFailure(404, 'webhook_not_found')

    const body = await c.req.text()
    try {
      await c.env.BC_INBOUND.send({
        kind: 'basecamp_webhook',
        bcWebhookId: hook.bc_webhook_id,
        bcProjectId: hook.bc_project_id,
        receivedAt: nowIso(),
        body,
      })
    } catch (error) {
      // Not 200: Basecamp keeps the delivery and retries it.
      console.error(`bc-inbound send failed for webhook ${hook.bc_webhook_id}: ${error instanceof Error ? error.name : 'unknown'}`)
      throw new ApiFailure(503, 'queue_unavailable')
    }

    return c.json({ ok: true })
  })

  return routes
}
