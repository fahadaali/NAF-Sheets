// Regenerates src/univer-functions.generated.ts from the installed
// @univerjs/engine-formula: the names in ALL_IMPLEMENTED_FUNCTIONS_SET,
// i.e. every function its formula engine can evaluate.
//
//   node packages/gsheets-import/scripts/generate-univer-functions.mjs
//
// test/univer-contract.test.ts fails when the file and the installed
// package disagree, so a Univer upgrade cannot leave the list stale.

import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { createRequire } from 'node:module'
import { ALL_IMPLEMENTED_FUNCTIONS_SET } from '@univerjs/engine-formula'

const here = dirname(fileURLToPath(import.meta.url))
const require = createRequire(import.meta.url)
// The package's exports map hides package.json; read it next to the resolved entry.
const entry = require.resolve('@univerjs/engine-formula')
const packageRoot = entry.slice(0, entry.lastIndexOf('/lib/'))
const { version } = JSON.parse(readFileSync(join(packageRoot, 'package.json'), 'utf8'))
const names = [...ALL_IMPLEMENTED_FUNCTIONS_SET].map(String).sort()

const lines = [
  '// GENERATED by scripts/generate-univer-functions.mjs — do not edit by hand.',
  `// Source: @univerjs/engine-formula@${version}, ALL_IMPLEMENTED_FUNCTIONS_SET (${names.length} names).`,
  '// Checked against the installed package by test/univer-contract.test.ts.',
  '',
  `export const UNIVER_FUNCTIONS_SOURCE_VERSION = '${version}'`,
  '',
  'export const UNIVER_IMPLEMENTED_FUNCTIONS: readonly string[] = [',
  ...names.map((n) => `  '${n}',`),
  ']',
  '',
]
writeFileSync(join(here, '..', 'src', 'univer-functions.generated.ts'), lines.join('\n'))
console.log(`wrote ${names.length} function names from @univerjs/engine-formula@${version}`)
